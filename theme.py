"""Дизайн-токены Wingman — единственный источник цветов для интерфейса и графиков.

Палитра из трёх цветов:
  * Midnight Black #030407 — текст и тёмные плоскости (обложка);
  * Electric Cobalt Blue #1558C9 — действия: кнопки, ссылки, выбранное;
  * Acid Lime #D4FF24 — редкий акцент: процент совпадения, «идёт сейчас», кнопка на чёрной обложке.

Лайм никогда не бывает текстом на белом: контраст ≈ 1,1:1. Только фон под чёрным текстом
(≈ 18:1) или текст на чёрном. Кобальт на белом ≈ 6,3:1 (WCAG AA для текста — 4,5:1).
"""

INK = "#030407"        # Midnight Black: основной текст
PRIMARY = "#1558C9"    # Electric Cobalt Blue: кнопки и ссылки
ACCENT = "#D4FF24"     # Acid Lime: акцент
SURFACE = "#F3F5F9"    # фон плашек и полей
BORDER = "#E3E6EC"     # рамки карточек
MUTED = "#5B6170"      # второстепенный текст — контраст с белым ≈ 6:1

# Цвет пары целей на дашборде: ищущий и тот, кто ему отвечает, получают один цвет.
PAIR_COLOR = {
    "job": PRIMARY,          # работа: ищу работу ↔ нанимаю
    "mentor": INK,           # менторство: ищу ментора ↔ стану ментором
    "cofounder": ACCENT,     # кофаундеры
    "exchange": "#8FB0EA",   # обмен опытом — светлый кобальт
}
PAIR_OF = {"find_job": "job", "hire": "job", "find_mentor": "mentor", "be_mentor": "mentor",
           "find_cofounder": "cofounder", "exchange": "exchange"}


def goal_color(goal: str) -> str:
    return PAIR_COLOR[PAIR_OF[goal]]


# Последовательная шкала для тепловой карты дашборда: от фона к кобальту.
HEATMAP_SCALE = [[0.0, SURFACE], [0.5, "#8FB0EA"], [1.0, PRIMARY]]

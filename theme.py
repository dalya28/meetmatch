"""Дизайн-токены MeetMatch — единственный источник цветов для интерфейса и графиков.

Идея: карточка рекомендации — это бейдж участника митапа. Цвет «ленты бейджа»
кодирует пару целей (работа, менторство, кофаундеры, обмен опытом), и тот же цвет
используется на дашборде организатора. Цвет несёт смысл, а не украшает.

Контраст каждого цвета с белым фоном ≥ 5:1 (WCAG AA для текста — 4.5:1),
поэтому цвета пар можно использовать и для текста.
"""

INK = "#1B2430"        # основной текст            — контраст с белым ≈ 15:1
PRIMARY = "#12355B"    # «Алатау»: кнопки, акценты  — ≈ 12:1
SURFACE = "#F2F5F8"    # фон полей и плашек
BORDER = "#D9E0E7"     # рамки карточек
MUTED = "#5B6573"      # второстепенный текст       — ≈ 6:1

# Цвет пары целей: ищущий и тот, кто ему отвечает, получают один цвет.
PAIR_COLOR = {
    "job": "#1F6FB2",        # работа: ищу работу ↔ нанимаю         — 5.3:1
    "mentor": "#23744A",     # менторство: ищу ментора ↔ стану ментором — 5.7:1
    "cofounder": "#96600F",  # кофаундеры                            — 5.3:1
    "exchange": "#6B4FA0",   # обмен опытом                          — 6.5:1
}
PAIR_OF = {"find_job": "job", "hire": "job", "find_mentor": "mentor", "be_mentor": "mentor",
           "find_cofounder": "cofounder", "exchange": "exchange"}


def goal_color(goal: str) -> str:
    return PAIR_COLOR[PAIR_OF[goal]]


